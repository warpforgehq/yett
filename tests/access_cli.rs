#[test]
fn removing_one_recipient_rotates_the_wrapped_key_for_the_others() {
    let dir = project();
    let alice = key(dir.path(), "alice.key");
    let bob = key(dir.path(), "bob.key");
    let carol = key(dir.path(), "carol.key");
    let secret_path = dir.path().join(".yett/secrets.dev.enc.yaml");
    std::fs::write(
        &secret_path,
        yett::sops::encrypt_yaml(PLAINTEXT, &alice.recipient).unwrap(),
    )
    .unwrap();
    write_access(
        dir.path(),
        &access_text(&[
            ("alice", "dev", &alice.recipient),
            ("bob", "dev", &bob.recipient),
            ("carol", "dev", &carol.recipient),
        ]),
    );
    let added = yett(
        dir.path(),
        &["--identity", alice.path.to_str().unwrap(), "access", "sync"],
    );
    assert_eq!(added.status.code(), Some(0), "{}", stderr(&added));
    let before = std::fs::read_to_string(&secret_path).unwrap();
    let bob_identity = identity_at(&bob.path);
    let bob_before = wrapped_data_key(&before, &bob_identity);

    let removed = yett(
        dir.path(),
        &[
            "--identity",
            alice.path.to_str().unwrap(),
            "access",
            "remove",
            "carol",
        ],
    );
    assert_eq!(removed.status.code(), Some(0), "{}", stderr(&removed));

    let after = std::fs::read_to_string(&secret_path).unwrap();
    assert_ne!(
        wrapped_data_key(&after, &bob_identity),
        bob_before,
        "the data key wrapped for bob must be a different key after carol is removed"
    );
    let yaml: serde_yaml::Value = serde_yaml::from_str(&after).unwrap();
    assert!(
        yaml["sops"]["age"]
            .as_sequence()
            .unwrap()
            .iter()
            .all(|entry| entry["recipient"].as_str() != Some(&carol.recipient)),
        "carol must not appear in the rewrapped metadata"
    );
}

#[test]
fn verification_reports_config_and_recipient_mismatches_as_exit_four() {
    let dir = project();
    let alice = key(dir.path(), "alice.key");
    let bob = key(dir.path(), "bob.key");
    write_access(
        dir.path(),
        &access_text(&[("alice", "dev", &alice.recipient)]),
    );
    let access =
        yett::access::AccessList::load(&dir.path().join(".yett/secrets-access.yaml")).unwrap();
    let edited = format!("{}# hand edit\n", access.render_sops_config());
    let error = yett::access::verify(&access, &edited, &dir.path().join(".yett")).unwrap_err();
    assert!(matches!(error, yett::Error::AccessMismatch(_)));
    assert_eq!(error.exit_code(), 4);
    println!("hand-edited .sops.yaml: AccessMismatch, exit 4");

    std::fs::write(
        dir.path().join(".yett/secrets.dev.enc.yaml"),
        yett::sops::encrypt_yaml(PLAINTEXT, &bob.recipient).unwrap(),
    )
    .unwrap();
    let error = yett::access::verify(
        &access,
        &access.render_sops_config(),
        &dir.path().join(".yett"),
    )
    .unwrap_err();
    assert!(matches!(error, yett::Error::AccessMismatch(_)));
    assert_eq!(error.exit_code(), 4);
    println!("extra file recipient: AccessMismatch, exit 4");
}
